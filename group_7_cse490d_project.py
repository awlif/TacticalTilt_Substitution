# Define simulate_substitutions function (copied from earlier in the notebook)
def simulate_substitutions(
    prediction_df,
    teams=("Argentina", "France"),
    threshold=0.50
):
    predictions = []
    for team in teams:
        team_data = prediction_df[prediction_df["team"] == team].copy()
        substituted_players = set()
        for minute in sorted(team_data["minute"].unique()):
            current = team_data[team_data["minute"] == minute].copy()
            current = current[~current["player"].isin(substituted_players)]
            if len(current) == 0:
                continue
            current = current.sort_values("substitution_probability", ascending=False)
            best = current.iloc[0]
            if (best["substitution_probability"] >= threshold):
                predictions.append({
                    "team": team,
                    "predicted_minute": minute,
                    "predicted_player_out": best["player"],
                    "probability": best["substitution_probability"]
                })
                substituted_players.add(best["player"])
    return pd.DataFrame(predictions)

# Define evaluate_substitution_predictions function (copied from earlier in the notebook)
def evaluate_substitution_predictions(
    predicted,
    actual,
    time_tolerance=300
):
    results = []
    for _, pred in predicted.iterrows():
        team = pred["team"]
        pred_time = pred["predicted_minute"] * 60
        pred_player = pred["predicted_player_out"]
        team_actual = actual[actual["team"] == team].copy()
        team_actual["time_difference"] = (team_actual["time_seconds"] - pred_time).abs()
        matches = team_actual[
            (team_actual["player_out"] == pred_player) &
            (team_actual["time_difference"] <= time_tolerance)
        ]
        results.append({
            "team": team,
            "predicted_player": pred_player,
            "predicted_minute": pred["predicted_minute"],
            "probability": pred["probability"],
            "correct": len(matches) > 0
        })
    return pd.DataFrame(results)

