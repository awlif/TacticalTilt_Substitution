def timestamp_to_seconds(timestamp):
    """
    Convert HH:MM:SS.sss timestamp to seconds.
    """

    if pd.isna(timestamp):
        return np.nan

    parts = str(timestamp).split(":")

    hours = int(parts[0])
    minutes = int(parts[1])
    seconds = float(parts[2])

    return hours * 3600 + minutes * 60 + seconds
