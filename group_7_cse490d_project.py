    match_player_df["second_half"] = (match_player_df["minute"] >= 45).astype(int)
    match_player_df["late_game"] = (match_player_df["minute"] >= 75).astype(int)
    match_player_df["very_late_game"] = (match_player_df["minute"] >= 90).astype(int)

    if match_player_df.empty: # Handle cases where no data could be generated for the match
        return 0.0, pd.DataFrame()

    match_player_df["substitution_probability"] = model.predict_proba(
        match_player_df[features_list].fillna(0)
    )[:, 1]

    predicted_subs_match = simulate_substitutions(
        match_player_df,
        teams=match_player_df["team"].unique(), # Get teams dynamically from the match data
        threshold=sub_threshold
    )

    actual_match_subs = substitutions_df[
        substitutions_df["match_id"] == match_id
    ].copy()

    if predicted_subs_match.empty and actual_match_subs.empty:
        return 1.0, pd.DataFrame() # No subs predicted, no subs happened, so 100% accurate for 0 subs
    elif predicted_subs_match.empty and not actual_match_subs.empty:
        return 0.0, pd.DataFrame() # No subs predicted, but subs happened
    elif not predicted_subs_match.empty and actual_match_subs.empty:
        return 0.0, pd.DataFrame() # Subs predicted, but no subs happened

    substitution_results = evaluate_substitution_predictions(
        predicted_subs_match,
        actual_match_subs,
        time_tolerance=time_tolerance
    )

    if not substitution_results.empty: # Check if there are any results to calculate mean from
        accuracy = substitution_results["correct"].mean()
    else:
        accuracy = 0.0 # Default accuracy if no comparable results

    return accuracy, substitution_results

