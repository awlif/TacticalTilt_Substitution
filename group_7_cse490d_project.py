def simulate_substitutions(
    prediction_df,
    teams=("Argentina", "France"),
    threshold=0.50
):
    predictions = []
    for team in teams:
        team_data = prediction_df[prediction_df["team"] == team].copy()
        substituted_players = set()
        for minute in sorted(team_data["minute"].unique()):
            current = team_data[team_data["minute"] == minute].copy()
            current = current[~current["player"].isin(substituted_players)]
            if len(current) == 0:
                continue
            current = current.sort_values("substitution_probability", ascending=False)
            best = current.iloc[0]
            if (best["substitution_probability"] >= threshold):
                predictions.append({
                    "team": team,
                    "predicted_minute": minute,
                    "predicted_player_out": best["player"],
                    "probability": best["substitution_probability"]
                })
                substituted_players.add(best["player"])
    return pd.DataFrame(predictions)

